    pub fn verifySignature(
        pk: runtime::JubjubPoint,
        signature: crate::types::Signature,
        challenge: runtime::Field,
    ) -> Result<bool, runtime::CompactError> {
        Ok({
            crate::pure_circuits::assertUsableJubjubPoint(pk)?;
            crate::pure_circuits::assertUsableJubjubPoint((signature.clone()).r)?;
            {
                let __compact_local_leftSide: runtime::JubjubPoint =
                    runtime::ec_mul_generator((signature.clone()).s)?;
                {
                    let __compact_local_cPk: runtime::JubjubPoint = runtime::ec_mul(pk, challenge)?;
                    {
                        let __compact_local_rightSide: runtime::JubjubPoint =
                            runtime::ec_add((signature.clone()).r, __compact_local_cPk);
                        {
                            let __compact_local_xMatches: bool =
                                runtime::jubjub_point_x(__compact_local_leftSide)
                                    == runtime::jubjub_point_x(__compact_local_rightSide);
                            {
                                let __compact_local_yMatches: bool =
                                    runtime::jubjub_point_y(__compact_local_leftSide)
                                        == runtime::jubjub_point_y(__compact_local_rightSide);
                                {
                                    if !(if __compact_local_xMatches {
                                        __compact_local_yMatches
                                    } else {
                                        false
                                    }) {
                                        return Err(runtime::CompactError::AssertionFailed(
                                            "Signature verification failed".to_owned(),
                                        ));
                                    }
                                    if __compact_local_xMatches {
                                        __compact_local_yMatches
                                    } else {
                                        false
                                    }
                                }
                            }
                        }
                    }
                }
            }
        })
    }
