    /// Groups the contract's exported circuits for Rust consumers.
    pub struct Contract<W> {
        #[allow(dead_code)]
        witnesses: W,
        pub recording: recorded::Contract,
    }
    impl<W> From<W> for Contract<W> {
        fn from(witnesses: W) -> Self {
            Self {
                witnesses,
                recording: recorded::Contract,
            }
        }
    }
    impl Default for Contract<()> {
        fn default() -> Self {
            Self {
                witnesses: (),
                recording: recorded::Contract,
            }
        }
    }
    impl<W> Contract<W> {
        pub fn write_once<Private>(
            &self,
            context: runtime::context::CircuitContext<Private>,
        ) -> Result<runtime::context::CircuitResult<Private, ()>, runtime::CompactError>
        where
            W: TryWitnesses<Private>,
        {
            crate::ledger_contract::write_once(context, &self.witnesses)
        }
        pub fn write_read<Private>(
            &self,
            context: runtime::context::CircuitContext<Private>,
            coin: crate::types::ShieldedCoinInfo,
            recipient: crate::types::Either,
        ) -> Result<
            runtime::context::CircuitResult<Private, crate::types::QualifiedShieldedCoinInfo>,
            runtime::CompactError,
        > {
            crate::ledger_contract::write_read(context, coin, recipient)
        }
        /// Borrow the contract's witnesses for a replayable circuit call.
        pub fn recording(&self) -> recorded::BorrowedContract<'_, W> {
            recorded::BorrowedContract {
                witnesses: &self.witnesses,
            }
        }
    }
