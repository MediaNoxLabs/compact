pub mod pure_circuits {
    use super::*;

    pub fn assert_record_fresh_enough(
        policy: FreshnessPolicy,
        record: AssetRecord,
        current_time: u64,
    ) -> Result<(), CompactError> {
        compact_assert!(
            (current_time >= record.provenance.registeredAt),
            "registration time cannot be in the future"
        );
        Ok(if policy.enforceMaxAge {
            let t = {
                let t_0 = record.provenance.registeredAt;
                {
                    compact_assert!(
                        (current_time >= t_0),
                        "result of subtraction would be negative"
                    );
                    ((current_time) as u64).wrapping_sub((t_0) as u64)
                }
            };
            compact_assert!((t <= policy.maxAge), "record exceeds the max-age policy");
        })
    }

    pub fn registration_gap(newer: AssetRecord, older: AssetRecord) -> Result<u64, CompactError> {
        let t = newer.provenance.registeredAt;
        compact_assert!(
            (t >= older.provenance.registeredAt),
            "newer record must not predate the older one"
        );
        let t_0 = newer.provenance.registeredAt;
        let t_1 = older.provenance.registeredAt;
        compact_assert!((t_0 >= t_1), "result of subtraction would be negative");
        Ok(((t_0) as u64).wrapping_sub((t_1) as u64))
    }

    pub fn assert_record_class_known(record: AssetRecord) -> Result<(), CompactError> {
        compact_assert!(
            (record.kind != AssetClass::Unspecified),
            "asset class must be specified"
        );
        Ok(())
    }

    pub fn assert_grant_not_future(grant: CustodyGrant, as_of: u64) -> Result<(), CompactError> {
        let t = grant.grantedAt;
        compact_assert!((t <= as_of), "grant is not yet effective");
        Ok(())
    }
}
