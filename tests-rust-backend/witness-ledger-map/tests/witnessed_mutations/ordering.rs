use crate::{ledger_contract as c, ledger_slots::table};
use midnight_compact_runtime as r;
use midnight_onchain_state::state::{ContractOperation, EntryPointBuf};
use midnight_serialize::{Deserializable, Serializable};
use r::context::{ConstructorContext, WitnessContext};
use r::recording::RecordingFrame;
use r::transaction::{
    Observation, ObservedCallError, ObservedContractState, PrepareCallError, VerifierKey,
};
use std::{cell::RefCell, rc::Rc};
type Events = Rc<RefCell<Vec<(u64, bool)>>>;
#[derive(Clone, Default)]
struct Witness {
    fail: bool,
    events: Events,
}
impl Witness {
    fn observe(&self, private: u64, present: bool) -> Result<(u64, bool), r::CompactError> {
        self.events.borrow_mut().push((private, present));
        if self.fail {
            return Err(r::CompactError::InvalidLedgerCell(
                "map provider refused".into(),
            ));
        }
        Ok((private + 1, present))
    }
}
impl c::TryWitnesses<u64> for Witness {
    fn has_true(
        &self,
        ctx: WitnessContext<'_, u64, c::LedgerView<'_>>,
    ) -> Result<(u64, bool), r::CompactError> {
        self.observe(*ctx.private_state, ctx.ledger.table()?.member(true)?)
    }
}
fn setup(populated: bool) -> (ObservedContractState, VerifierKey) {
    let mut context = c::initial_state(ConstructorContext::new(7_u64))
        .unwrap()
        .into_circuit_context(Default::default());
    if populated {
        context = table
            .insert(context, true, r::Field::from(42_u64))
            .unwrap()
            .context;
    }
    // Preparation carrier only; no proof is generated by these tests.
    let mut bytes = Vec::new();
    Vec::<u8>::new().serialize(&mut bytes).unwrap();
    let key = VerifierKey::deserialize(&mut bytes.as_slice(), 0).unwrap();
    let operations = r::ledger::LedgerHashMap::new().insert(
        EntryPointBuf(b"mutate_witnessed".to_vec()),
        ContractOperation::new(Some(key.clone())),
    );
    (
        ObservedContractState::new(
            Default::default(),
            r::ledger::ContractState::new(
                context.query.state.get_ref().clone(),
                operations,
                Default::default(),
            ),
            Observation {
                transaction_hash: [0; 32],
                block_hash: [0; 32],
                block_height: 0,
            },
        ),
        key,
    )
}
fn manual(
    state: &ObservedContractState,
    w: &Witness,
    selected: bool,
) -> Result<r::recording::RecordedCircuitResult<u64, ()>, r::CompactError> {
    let mut frame = RecordingFrame::new(state.circuit_context(7));
    if selected {
        let (next, key) = frame.try_witness_metered(|ctx, meter| {
            w.observe(ctx.private_state, table.witness_view(meter)?.member(true)?)
        })?;
        frame = table.record_insert_default(next, key)?;
        // Non-query inspection adds no operation/gas absent from generated code.
        assert_eq!(
            table
                .inspect(frame.context().query.state.get_ref())?
                .lookup(key)?,
            r::Field::from(0_u64)
        );
        frame = table.record_reset(frame)?;
    }
    Ok(frame.finish(()))
}
#[test]
fn lazy_witness_default_then_reset_matches_all_lanes_and_preparation() {
    for (selected, populated) in [(true, true), (true, false), (false, true)] {
        let (state, key) = setup(populated);
        let a = Witness::default();
        let b = Witness::default();
        let w = Witness::default();
        let m = Witness::default();
        let native = c::mutate_witnessed(state.circuit_context(7), &a, selected).unwrap();
        let recorded =
            c::recorded::mutate_witnessed(state.circuit_context(7), &b, selected).unwrap();
        let contract = c::Contract::from(w.clone());
        let call = contract
            .recording()
            .mutate_witnessed_call(&state, 7, selected)
            .unwrap();
        let manual = manual(&state, &m, selected).unwrap();
        let outputs = if selected {
            vec![r::fab::AlignedValue::from(populated)]
        } else {
            vec![]
        };
        let events = if selected {
            vec![(7, populated)]
        } else {
            vec![]
        };
        assert_eq!(native.private_transcript_outputs, outputs);
        assert_eq!(native.context.private_state, 7 + u64::from(selected));
        let expected = manual
            .public
            .initial()
            .query(manual.public.verify_ops(), None, &native.context.cost_model)
            .unwrap();
        for actual in [&recorded, call.recorded(), &manual] {
            assert_eq!(
                actual.execution.context.query.state,
                native.context.query.state
            );
            assert_eq!(
                actual.execution.context.query.effects,
                native.context.query.effects
            );
            assert_eq!(actual.execution.gas_cost, native.gas_cost);
            assert_eq!(
                actual.execution.context.private_state,
                native.context.private_state
            );
            assert_eq!(actual.execution.private_transcript_outputs, outputs);
            assert_eq!(actual.public.verify_ops(), manual.public.verify_ops());
            let replay = actual
                .public
                .initial()
                .query(actual.public.verify_ops(), None, &native.context.cost_model)
                .unwrap();
            assert_eq!(replay.context.state, native.context.query.state);
            assert_eq!(replay.context.effects, native.context.query.effects);
            assert_eq!(replay.gas_cost, expected.gas_cost);
        }
        for provider in [&a, &b, &w, &m] {
            assert_eq!(*provider.events.borrow(), events);
        }
        assert_eq!(
            table
                .inspect(native.context.query.state.get_ref())
                .unwrap()
                .size()
                .unwrap()
                .value(),
            u128::from(!selected && populated)
        );
        if selected {
            let prepared = call.prepare(key, r::Field::from(0_u64)).unwrap();
            assert_eq!(prepared.input, r::fab::AlignedValue::from(selected));
            assert_eq!(prepared.output, r::fab::AlignedValue::from(()));
        } else {
            assert!(recorded.public.verify_ops().is_empty());
            assert!(matches!(
                call.prepare(key, r::Field::from(0_u64)),
                Err(ObservedCallError::Prepare(
                    PrepareCallError::EmptyTranscript
                ))
            ));
        }
    }
}
#[test]
fn provider_failure_precedes_mutation_and_unselected_branch_suppresses_it() {
    for selected in [true, false] {
        for lane in 0..4 {
            let (state, _) = setup(true);
            let w = Witness {
                fail: true,
                ..Default::default()
            };
            let contract = c::Contract::from(w.clone());
            let result = match lane {
                0 => c::mutate_witnessed(state.circuit_context(7), &w, selected).map(|_| ()),
                1 => c::recorded::mutate_witnessed(state.circuit_context(7), &w, selected)
                    .map(|_| ()),
                2 => contract
                    .recording()
                    .mutate_witnessed_call(&state, 7, selected)
                    .map(|_| ()),
                _ => manual(&state, &w, selected).map(|_| ()),
            };
            if selected {
                assert!(
                    matches!(result,Err(r::CompactError::InvalidLedgerCell(ref detail)) if detail=="map provider refused")
                );
                assert_eq!(*w.events.borrow(), vec![(7, true)]);
            } else {
                assert!(result.is_ok());
                assert!(w.events.borrow().is_empty());
            }
            assert_eq!(
                table
                    .inspect(state.contract().data.get_ref())
                    .unwrap()
                    .lookup(true)
                    .unwrap(),
                r::Field::from(42_u64)
            );
        }
    }
}
